    public Main() {
        ManagePanel.initPanels();
        taskPanel = ManagePanel.getTasksPanel();
        progressPanel = ManagePanel.getProgressPanel();
        calendarPanel = ManagePanel.getCalendarPanel();
        timerPanel = ManagePanel.getTimerPanel();
        
        initComponents();
        setBackground(new Color(0,0,0,0));
        
        panelBorder1.setBackground(new Color(255, 250, 250));
        
        // To move the application using the menu
        setPanel(taskPanel);
        //setPanel(taskPanel);
        
        menu.initMoving(Main.this);
        menu.addEventMenuSelected((int index) -> {
            switch (index) {
                case 0 -> {taskPanel.refresh(); setPanel(taskPanel);}
                case 1 -> setPanel(progressPanel); 
                case 2 -> setPanel(calendarPanel);
                case 3 -> setPanel(timerPanel);
                default ->setPanel(taskPanel);
            }
        });
        
        setVisible(true);
    }
    
    private void setPanel(JComponent com) {
        mainPanel.removeAll();
        mainPanel.add(com);
        mainPanel.repaint();
        mainPanel.revalidate();
    }
   

